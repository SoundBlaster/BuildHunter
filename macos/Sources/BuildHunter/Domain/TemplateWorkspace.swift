import Foundation
import Observation

/// One draft survives closing Settings; source files remain user-owned.
@MainActor
@Observable
final class TemplateWorkspace {
    static let shared = TemplateWorkspace(library: .shared)
    let library: TemplateLibrary
    var text = ""
    private(set) var reference: TemplateReference?
    private(set) var original: Data?
    private(set) var message = "Connect a JSON file or create a new template."
    private(set) var isError = false
    private(set) var busy = false
    private(set) var hasDocument = false

    init(library: TemplateLibrary) { self.library = library }

    var isDirty: Bool { hasDocument && Data(text.utf8) != original }

    func newDocument() {
        guard !busy else { return }
        reference = nil
        original = nil
        text = TemplateCatalog.example()
        hasDocument = true
        message = "Unsaved template. Edit the example or paste JSON generated by your agent."
        isError = false
    }

    func load(_ reference: TemplateReference) async {
        guard !busy else { return }
        busy = true
        defer { busy = false }
        do {
            let (bytes, renewed) = try await TemplateOperations.read(reference)
            guard let text = String(data: bytes, encoding: .utf8) else {
                throw TemplateProblem(code: "invalid_utf8", location: reference.path, message: "The file is not UTF-8 JSON.")
            }
            if library.references.contains(where: { $0.id == reference.id }) { try library.connect(renewed) }
            self.reference = renewed
            original = bytes
            self.text = text
            hasDocument = true
            message = "Loaded \(reference.path). Check validates the saved files and the selected draft."
            isError = false
        } catch {
            // A failed reload preserves the user's existing draft.
            fail(error)
        }
    }

    func check() async {
        guard !busy, hasDocument else { return }
        busy = true
        defer { busy = false }
        let bytes = Data(text.utf8)
        let references = library.references
        let selectedID = reference?.id
        do {
            if let problem = library.storageProblem {
                throw TemplateProblem(code: "invalid_registry", location: "", message: problem)
            }
            let metadata = try await TemplateOperations.check(references, draft: bytes, selectedID: selectedID)
            message = "Valid catalog · \(metadata.targets.count) targets · \(metadata.digest.prefix(12))"
            isError = false
        } catch { fail(error) }
    }

    func save() async {
        guard !busy, let reference, let original else { return }
        busy = true
        defer { busy = false }
        let bytes = Data(text.utf8)
        do {
            let renewed = try await TemplateOperations.save(reference, bytes: bytes, expected: original)
            if library.references.contains(where: { $0.id == reference.id }) { try library.connect(renewed) }
            self.reference = renewed
            self.original = bytes
            message = "Saved. New scans reload the connected file."
            isError = false
        } catch { fail(error) }
    }

    func saveAs(_ url: URL) async {
        guard !busy else { return }
        busy = true
        defer { busy = false }
        let bytes = Data(text.utf8)
        do {
            try library.validateConnection(path: url.standardizedFileURL.path)
            // Save As writes the chosen destination but never changes another registration.
            let connected = try await TemplateOperations.saveAs(url, bytes: bytes)
            try library.connect(connected)
            reference = library.references.first { $0.path == connected.path }
            original = bytes
            hasDocument = true
            message = "Saved and connected. New scans reload this file."
            isError = false
        } catch { fail(error) }
    }

    func connect(_ urls: [URL]) async {
        guard !busy else { return }
        busy = true
        defer { busy = false }
        do {
            for url in urls {
                let reference = try await TemplateOperations.connect(url)
                try library.connect(reference)
                if self.reference?.path == reference.path {
                    self.reference = library.references.first { $0.path == reference.path }
                }
            }
            message = "Files connected. Check the catalog before scanning; disable invalid files explicitly."
            isError = false
        } catch { fail(error) }
    }

    func explain(_ message: String) { self.message = message; isError = true }

    private func fail(_ error: Error) { message = error.localizedDescription; isError = true }
}

enum TemplateOperations {
    @concurrent static func read(_ reference: TemplateReference) async throws -> (Data, TemplateReference) {
        (try TemplateFiles.read(reference), try TemplateFiles.renewed(reference))
    }

    @concurrent static func connect(_ url: URL) async throws -> TemplateReference {
        // Retain a broken JSON registration so its status can be fixed in the editor.
        let reference = try TemplateReference.connect(url)
        _ = try TemplateFiles.read(reference)
        return reference
    }

    @concurrent static func check(_ references: [TemplateReference], draft: Data, selectedID: UUID?) async throws -> ScanCatalogMetadata {
        // Validate a disabled draft too, but never quietly activate it in the effective catalog.
        _ = try TemplateCatalog.metadata(documents: [draft])
        var documents: [Data] = []
        var total = 0
        for reference in references where reference.enabled {
            let bytes = reference.id == selectedID ? draft : try TemplateFiles.read(reference)
            total += bytes.count
            guard total <= TemplateCatalog.maximumCatalogBytes else {
                throw TemplateProblem(code: "limit_exceeded", location: "", message: "Catalog byte limit exceeded.")
            }
            documents.append(bytes)
        }
        if selectedID == nil { documents.append(draft) }
        return try TemplateCatalog.metadata(documents: documents)
    }

    @concurrent static func save(_ reference: TemplateReference, bytes: Data, expected: Data) async throws -> TemplateReference {
        try TemplateFiles.save(reference, bytes: bytes, expected: expected)
        return try TemplateFiles.renewed(reference)
    }

    @concurrent static func saveAs(_ url: URL, bytes: Data) async throws -> TemplateReference {
        _ = try TemplateCatalog.metadata(documents: [bytes])
        let scoped = url.startAccessingSecurityScopedResource()
        defer { if scoped { url.stopAccessingSecurityScopedResource() } }
        try bytes.write(to: url, options: .atomic)
        return try TemplateReference.connect(url)
    }
}
